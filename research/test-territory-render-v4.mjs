import assert from 'node:assert/strict';
import {rendererPlan,completeParity,parityFeatures,inspectAdapter} from '../dist/js/territory-backend-policy.js';
import {shadowPlan,contactPlan,estimateTargetBytes} from '../dist/js/territory-render-policy.js';
const ready={entry:true,verified:Object.fromEntries(parityFeatures.map(k=>[k,true]))};
assert.equal(rendererPlan({secure:true,adapter:true}).preferred,'webgl2');
assert.equal(rendererPlan({request:'webgpu',secure:true,adapter:true}).preferred,'webgpu');
assert.equal(rendererPlan({request:'webgpu',secure:true,adapter:true,software:true}).preferred,'webgl2');
assert.equal(rendererPlan({request:'webgpu',secure:false,adapter:true}).preferred,'webgl2');
assert.equal(rendererPlan({request:'webgpu',secure:true,adapter:true,candidate:{entry:false,verified:{}}}).preferred,'webgl2');
assert.equal(rendererPlan({secure:true,adapter:true,scope:'lab'}).preferred,'webgpu');
assert.equal(rendererPlan({secure:true,adapter:true,software:true,scope:'lab'}).preferred,'webgl2');
assert.equal(rendererPlan({secure:false,adapter:true,scope:'lab'}).preferred,'webgl2');
assert.equal(rendererPlan({request:'webgl2',secure:true,adapter:true,scope:'lab'}).preferred,'webgl2');
assert.equal(rendererPlan({secure:true,adapter:true,candidate:ready}).preferred,'webgpu');
assert.equal(completeParity({...ready,entry:false}),false);
assert.equal(completeParity({entry:true,verified:{...ready.verified,'water-planar-reflection':false}}),false);
assert.deepEqual(rendererPlan({secure:true,adapter:true,candidate:ready}).candidates,['webgpu','webgl2']);
assert.equal((await inspectAdapter(null,true)).available,false);
assert.equal((await inspectAdapter({requestAdapter:async()=>null},true)).available,false);
assert.equal((await inspectAdapter({requestAdapter:async()=>({info:{isFallbackAdapter:true},limits:{maxTextureDimension2D:8192}})},true)).software,true);
assert.equal((await inspectAdapter({requestAdapter:async()=>{throw Error('device');}},true)).available,false);
assert.equal(shadowPlan({range:71,quality:2,previousExtent:85}).extent,85);
assert.equal(shadowPlan({range:85,quality:2,previousExtent:85}).extent,145);
assert.equal(shadowPlan({range:10,quality:3,maxTextureSize:2048}).size,2048);
assert.equal(shadowPlan({range:10,quality:3,aboveHorizon:false}).enabled,false);
assert.equal(shadowPlan({range:6000,quality:3,atlasMode:true}).enabled,false);
assert.ok(shadowPlan({range:10,quality:3}).texel<shadowPlan({range:800,quality:3}).texel);
assert.equal(contactPlan({enabled:true,pixels:4500000}).samples,0);
assert.equal(contactPlan({enabled:true,pixels:2500000}).samples,2);
assert.equal(contactPlan({enabled:true,pixels:1000000,maxSamples:2}).samples,2);
assert.equal(contactPlan({enabled:false,pixels:1000000}).enabled,false);
assert.equal(estimateTargetBytes(100,100,0),120000);
console.log('OK: backend capability/parity gates and render budgets');
