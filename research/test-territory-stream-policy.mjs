import assert from 'node:assert/strict';
import {movementLead,selectSectors,heritageWindow,closeFabricBudget} from '../dist/js/territory-stream-policy.js';
assert.equal(movementLead(0,0,10,0,.05,'orbit',2),null);
assert.equal(movementLead(0,0,500,0,.05,'fly',2),null);
assert.equal(movementLead(0,0,0,0,.05,'walk',2),null);
assert.deepEqual(movementLead(0,0,2,0,.1,'fly',2),{x:90,z:0,length:90});
assert.ok(movementLead(0,0,40,0,.05,'fly',0).length<=260);
const tiles=Array.from({length:12},(_,i)=>({id:String(i),bounds:[i*100,-50,i*100+99,50]}));
assert.equal(selectSectors(tiles,50,0,300,3,new Map(),{x:500,z:0})[0][0].id,'0');
assert.equal(selectSectors(tiles,50,0,0,3,new Map(),null).length,0);
assert.equal(selectSectors(tiles,50,0,300,2,new Map(),{x:500,z:0}).length,2);
assert.ok(selectSectors(tiles,50,0,300,10,new Map([['4',{}]]),{x:500,z:0}).some(([s])=>s.id==='4'));
const initial={distance:80,ahead:Infinity,range:30,reach:260,close:100,loaded:false,native:false,selected:false,stop:false,quality:2,mobile:false};
assert.equal(heritageWindow(initial).full,true);
assert.equal(heritageWindow({...initial,distance:580,range:40}).warm,true);
assert.equal(heritageWindow({...initial,distance:4000,range:6000}).visible,false);
assert.equal(heritageWindow({...initial,distance:4500,range:3000,stop:true}).full,true);
assert.ok(closeFabricBudget(2,20).reach>closeFabricBudget(0,20).reach);
assert.ok(closeFabricBudget(2,20).count>closeFabricBudget(2,90).count);
console.log('OK: predictive lead, sector caps/priority, heritage window and close facade budgets');
