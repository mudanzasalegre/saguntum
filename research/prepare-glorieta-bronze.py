"""Reproducir los mapas compactos de pátina y epigrafía de la foto de dominio público."""
from pathlib import Path
import base64
import numpy as np
from PIL import Image, ImageFilter

root = Path(__file__).resolve().parents[1]
photo = Image.open(root / 'research/glorieta/romeu-2009.jpg').convert('L')
def encoded(image):
    return base64.b64encode(np.asarray(image, dtype='uint8').tobytes()).decode()
# Front colour is recovered on the traced silhouette only. Limit directional shade
# in the source so the bronze can receive the 3D scene's moving lights.
crop = photo.crop((135, 48, 304, 433)).resize((112, 256), Image.Resampling.LANCZOS)
a = np.asarray(crop, dtype=float)
bronze = np.clip(72 + a*.55, 66, 158)
# A local contrast estimate on the original inscription preserves the lettering
# without imprinting white rectangles or a cast shadow on the pedestal.
inscription = photo.crop((155, 495, 313, 582)).resize((224, 124), Image.Resampling.LANCZOS)
shade = np.asarray(inscription.filter(ImageFilter.GaussianBlur(4)),dtype=float)
engraving = np.clip(229+(np.asarray(inscription,dtype=float)-shade)*1.4,63,244)
def export(name, pixels):
    h,w=pixels.shape
    return f"export const {name}={{width:{w},height:{h},grey:'{encoded(pixels)}'}};\n"
output = '// Generated by research/prepare-glorieta-bronze.py from the attributed Commons photograph.\n'
# This square samples clean stone above the right shoulder, above the shadow.
sample = photo.crop((252, 38, 348, 110)).resize((96, 72), Image.Resampling.LANCZOS)
grain = np.asarray(sample,dtype=float)
limestone = np.clip(230+(grain - np.mean(grain))*.62, 206, 244)
output += export('portrait',bronze) + export('dedication',engraving) + export('limestone',limestone)
(root / 'dist/js/glorieta-romeu-patina.js').write_text(output,encoding='ascii')
